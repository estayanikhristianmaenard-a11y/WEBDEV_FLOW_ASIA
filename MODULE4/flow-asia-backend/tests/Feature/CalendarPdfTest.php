<?php

use Database\Seeders\DemoSeeder;
use FlowAsia\Module4\Models\CompanyEvent;
use FlowAsia\Module4\Models\Employee;
use FlowAsia\Module4\Models\User;
use FlowAsia\Module4\Services\CalendarPdfData;

beforeEach(function () {
    $this->seed(DemoSeeder::class);
});

it('downloads a real landscape PDF for the permitted employee', function () {
    $user = User::where('email', 'employee@test.com')->firstOrFail();
    $response = $this->actingAs($user)->get('/calendar/employees/'.$user->employee_id.'/pdf?month=2026-10')
        ->assertOk()->assertHeader('Content-Type', 'application/pdf');
    expect($response->getContent())->toStartWith('%PDF-');
    expect($response->headers->get('Content-Disposition'))->toContain('attachment', '.pdf');
    expect($response->headers->get('Cache-Control'))->toContain('no-store');
    preg_match('/\/MediaBox\s*\[\s*0(?:\.0+)?\s+0(?:\.0+)?\s+([\d.]+)\s+([\d.]+)/', $response->getContent(), $size);
    expect($size)->toHaveCount(3);
    expect((float) $size[1])->toBeGreaterThan((float) $size[2]);
});

it('denies guests, other employees and other teams', function () {
    $employee = Employee::where('employee_no', 'EMP-009')->firstOrFail();
    $url = '/calendar/employees/'.$employee->id.'/pdf?month=2026-10';
    $this->getJson($url)->assertUnauthorized();
    foreach (['employee@test.com', 'supervisor@test.com'] as $email) {
        $this->actingAs(User::where('email', $email)->firstOrFail())->getJson($url)->assertForbidden();
    }
});

it('allows HR and supervisor direct reports and validates months', function () {
    $employee = Employee::where('employee_no', 'EMP-002')->firstOrFail();
    foreach (['hr@test.com', 'supervisor@test.com'] as $email) {
        $this->actingAs(User::where('email', $email)->firstOrFail())
            ->get('/calendar/employees/'.$employee->id.'/pdf?month=2026-10')->assertOk();
    }
    $this->getJson('/calendar/employees/'.$employee->id.'/pdf?month=2026-13')->assertUnprocessable();
});

it('preserves secondary statuses, inclusive overlapping events and escaped event text', function () {
    $user = User::where('email', 'hr@test.com')->firstOrFail();
    $employee = Employee::where('employee_no', 'EMP-002')->firstOrFail();
    CompanyEvent::create(['title' => '<script>event</script>', 'type' => 'other', 'starts_on' => '2026-09-30', 'ends_on' => '2026-10-02']);
    $data = app(CalendarPdfData::class)->build($employee, $user, '2026-10');
    $days = collect($data['weeks'])->flatten(1)->filter()->keyBy('day');
    expect($days[12]['codes'])->toBe(['H', 'AL']);
    expect($data['summary']['leave_approved'])->toBe(4);
    expect($data['summary']['holiday'])->toBe(4);
    expect($days[1]['events'])->toHaveCount(1);
    expect($days[2]['events'])->toHaveCount(1);
    expect($days[3]['events'])->toHaveCount(0);
    $html = view('m4::pdf.employee-calendar', $data)->render();
    expect($html)->toContain('&lt;script&gt;event&lt;/script&gt;', 'Generated by', $user->name);
    expect($html)->not->toContain('<script>event</script>');
});

it('keeps missing days empty and handles leap months', function () {
    $employee = Employee::where('employee_no', 'EMP-040')->firstOrFail();
    $user = User::where('email', 'hr@test.com')->firstOrFail();
    $data = app(CalendarPdfData::class)->build($employee, $user, '2028-02');
    expect($data['missingDays'])->toBe(29);
    expect(array_sum($data['summary']))->toBe(0);
    expect(collect($data['weeks'])->flatten(1)->filter())->toHaveCount(29);
});
